def up_corner_permutation(cube: Cube) -> tuple[int, ...]:
    """
    Returns where each UP-layer corner belongs, in the slot order of PLL_UP_CORNER_STICKERS.

    Each corner is identified by the pair of colors on its two side stickers, and the slot it
    belongs in is the one lying between the two centers showing that pair of colors. The entry for
    a slot is therefore the index of the slot whose piece is currently sitting in it, and a solved
    last layer reads as (0, 1, 2, 3).

    :param cube: The Cube instance to read
    :return: The index of the home slot of the corner in each slot
    """

    home_colors = [
        frozenset(face_center_color(cube, layer) for layer, _ in stickers)
        for stickers in PLL_UP_CORNER_STICKERS.values()
    ]

    return tuple(
        home_colors.index(frozenset(cube.layers[layer][sticker] for layer, sticker in stickers))
        for stickers in PLL_UP_CORNER_STICKERS.values()
    )


def up_edge_permutation(cube: Cube) -> tuple[int, ...]:
    """
    Returns where each UP-layer edge belongs, in the slot order of PLL_UP_EDGE_STICKERS.

    Each edge is identified by the color on its side sticker, and the slot it belongs in is the one
    on the face whose center shows that color. The entry for a slot is therefore the index of the
    slot whose piece is currently sitting in it, and a solved last layer reads as (0, 1, 2, 3).

    :param cube: The Cube instance to read
    :return: The index of the home slot of the edge in each slot
    """

    home_colors = [face_center_color(cube, layer) for layer, _ in PLL_UP_EDGE_STICKERS.values()]

    return tuple(home_colors.index(cube.layers[layer][sticker]) for layer, sticker in PLL_UP_EDGE_STICKERS.values())
